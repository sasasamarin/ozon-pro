def parse_warehouse_name(name: str | None) -> tuple[str | None, str | None]:
    """Возвращает (city, cluster) из имени склада Ozon.

    Примеры:
      "ПУШКИНО_2_РФЦ" → ("Пушкино", "Москва")
      "Санкт_Петербург_РФЦ" → ("Санкт-Петербург", "СПб")
      "Краснодар_2_РФЦ" → ("Краснодар", "Юг")
      "НЕИЗВЕСТНОЕ_РФЦ" → ("Неизвестное", "Неизвестное")
    """
    if not name:
        return None, None
    # Убираем "_РФЦ", "_НОВЫЙ", цифровые суффиксы "_2", регион из конца
    cleaned = name.replace("_РФЦ", "").replace("_НОВЫЙ", "").replace("_СЦ", "")
    cleaned = re.sub(r"_\d+$", "", cleaned)
    cleaned = cleaned.replace("_", " ").strip()
    # Capitalize первое слово (Ozon шлёт в верхнем регистре часто)
    city = " ".join(w.capitalize() if not w.isalpha() or len(w) > 2 else w.capitalize() for w in cleaned.split())
    # Спецкейсы — нормализация
    city_norm = city.replace("Спб", "Санкт-Петербург").replace("СПб", "Санкт-Петербург")
    # ПУШКИНО → Пушкино, и т.п.
    # Поиск в карте — пробуем разные варианты
    for candidate in (city_norm, city_norm.replace(" ", "-"), city_norm.replace("-", " "), city_norm.title()):
        cluster = _CITY_TO_CLUSTER.get(candidate)
        if cluster:
            return candidate, cluster
    # Default: city = первое слово, cluster = тот же
    first_word = city_norm.split()[0] if city_norm else "(не определён)"
    cluster = _CITY_TO_CLUSTER.get(first_word, first_word)
    return city_norm or None, cluster
